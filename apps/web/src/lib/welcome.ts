export const WELCOME_BODY = `Vigil is a notebook where helpers work alongside you. Your notes are plain markdown files on your own disk; nothing here is locked in.

## Try writing
Select any text for a small toolbar, or type / at the start of a line to insert a heading, list, table or callout. Link to another note with [[double brackets]], and tag with #getting-started.

> [!tip] Press ? any time to see every shortcut, and Cmd or Ctrl plus K to search or run a command.

## Helpers
Helpers read your notes and write new ones, on a schedule or when you ask. Open Helpers to add one. Everything a helper writes can be undone, and you can ask one to wait for your approval first.

## Study
Write a question and an answer on one line, separated by two colons, and it becomes a card. Hide part of a sentence with double braces for a fill-in-the-blank. Open Study to review them; the app spaces the reviews out for you.

## Cards
What do you write to make a flashcard? :: A question, two colons, then the answer
Where does a hidden word go in a fill-in-the-blank card? :: Inside double braces
The {{Study}} page shows which cards are ready to review today.
`;
